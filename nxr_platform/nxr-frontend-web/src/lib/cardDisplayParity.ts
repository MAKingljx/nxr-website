import type { PublicCardDetail } from './api'

type CardDisplayInput = Pick<
  PublicCardDetail,
  | 'brandName'
  | 'cardCategory'
  | 'cardName'
  | 'filmType'
  | 'finalGradeLabel'
  | 'finalGradeValue'
  | 'groupName'
  | 'movieName'
  | 'playerName'
  | 'releaseYear'
  | 'varietyName'
>

const languageLabels: Record<string, string> = {
  EN: 'English',
  ENGLISH: 'English',
  JP: 'Japanese',
  JA: 'Japanese',
  JAPANESE: 'Japanese',
  CT: 'Chinese Traditional',
  'TRADITIONAL CHINESE': 'Chinese Traditional',
  'CHINESE TRADITIONAL': 'Chinese Traditional',
  CS: 'Chinese Simplified',
  'SIMPLIFIED CHINESE': 'Chinese Simplified',
  'CHINESE SIMPLIFIED': 'Chinese Simplified',
  ZH: 'Chinese',
}

export function pythonLanguageLabel(value: string | null | undefined) {
  const normalized = value?.trim() ?? ''
  return languageLabels[normalized.toUpperCase()] ?? normalized
}

export function pythonGradeText(card: Pick<CardDisplayInput, 'finalGradeLabel' | 'finalGradeValue'>) {
  const label = card.finalGradeLabel?.trim()
  if (label) return label
  return card.finalGradeValue === null ? '' : Number(card.finalGradeValue).toFixed(1)
}

export function pythonAiCopy(category: string | null | undefined) {
  switch (category) {
    case 'movie_film':
      return { button: 'AI Film Info', subtitle: 'Learn about this film', modal: 'AI Film Information' }
    case 'sports_card':
      return { button: 'AI Player Info', subtitle: 'Learn about this player', modal: 'AI Player Information' }
    case 'celebrity_card':
      return { button: 'AI Celebrity Info', subtitle: 'Learn about this celebrity', modal: 'AI Celebrity Information' }
    default:
      return { button: 'AI Character Info', subtitle: 'Learn about this character', modal: 'AI Character Information' }
  }
}

function cleanVideoSubject(value: string | null | undefined) {
  return (value ?? '')
    .trim()
    .replace(/\s*\d{10}$/, '')
    .replace(/\s+(EX|GX|VMAX|VSTAR|V)\s*$/i, '')
    .replace(/\s+(Rookie|Auto|Logoman|RPA)\s*$/i, '')
    .replace(/\s{2,}/g, ' ')
    .replace(/^[\s\-_/]+|[\s\-_/]+$/g, '')
}

function pythonVideoBrand(value: string | null | undefined) {
  const brand = (value ?? '').trim().toLowerCase()
  if (['pokemon', 'poke', 'pokemon jpn', '宝可梦'].includes(brand)) return 'pokemon'
  if (['yu-gi-oh!', '游戏王'].includes(brand)) return 'yugioh'
  if (['dragon ball', '龙珠'].includes(brand)) return 'dragonball'
  if (['one piece', '海贼王', '海贼'].includes(brand)) return 'onepiece'
  if (['sports cards', 'sports card', 'panini prizm', 'panini', 'upper deck', 'topps', 'bowman chrome'].includes(brand)) return 'sports'
  return 'generic'
}

export function pythonVideoAction(card: CardDisplayInput) {
  const brand = pythonVideoBrand(card.brandName)
  const baseName = cleanVideoSubject(card.movieName || card.cardName)
  const playerName = cleanVideoSubject(card.playerName)
  const subject = brand === 'sports' ? playerName || baseName : baseName || playerName
  if (!subject) return null

  let query: string
  let label: string
  let subtitle: string
  if (card.cardCategory === 'movie_film') {
    query = [subject, card.releaseYear, card.filmType || card.varietyName, 'movie film'].filter(Boolean).join(' ')
    label = 'Search Film'
    subtitle = 'Open a YouTube search for related film videos'
  } else if (card.cardCategory === 'celebrity_card') {
    query = [subject, card.groupName, 'celebrity card'].filter(Boolean).join(' ')
    label = 'Search Videos'
    subtitle = 'Open a YouTube search for related celebrity videos'
  } else if (brand === 'pokemon' || brand === 'yugioh' || brand === 'dragonball' || brand === 'onepiece') {
    const prefix = brand === 'pokemon' ? 'Pokemon' : brand === 'yugioh' ? 'Yu-Gi-Oh!' : brand === 'dragonball' ? 'Dragon Ball' : 'One Piece'
    query = `${prefix} ${subject} anime`
    label = 'Watch Anime'
    subtitle = 'Open a YouTube search for related anime clips'
  } else if (brand === 'sports') {
    query = `${subject} rookie highlights`
    label = 'Watch Highlights'
    subtitle = 'Open a YouTube search for player highlights'
  } else {
    query = `${subject} card overview`
    label = 'Search on YouTube'
    subtitle = 'Open a YouTube search for related card videos'
  }

  return { href: `https://www.youtube.com/results?search_query=${encodeURIComponent(query)}`, label, subtitle }
}

export function aiProviderNotice(provider: string, cached: boolean) {
  if (!provider) return ''
  if (provider === 'deepseek') return cached ? 'Cached DeepSeek AI context.' : 'Generated by DeepSeek AI.'
  if (provider.startsWith('local')) return 'Showing NXR local card context. Configure DeepSeek for expanded AI context.'
  return ''
}
